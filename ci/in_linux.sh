#!/bin/bash
# Runs INSIDE the godot-linux build container (godotengine/build-containers), from ci/build.sh:
# the Linux x86_64 Mono editor, the C# glue and GodotSharp assemblies (with their NuGet packages), then the
# export templates (debug; release with separate debug symbols). Mounts: /root/godot (patched source),
# /root/accesskit, /root/out.
set -euo pipefail
trap 'chown -R "${HOST_UID:-0}:${HOST_GID:-0}" /root/godot /root/out' EXIT

SCONS="scons -j${NUM_CORES} verbose=yes warnings=no progress=no redirect_build_objects=no precision=double"
OPTIONS="production=yes accesskit_sdk_path=/root/accesskit/accesskit-c module_mono_enabled=yes"
SYMBOLS="debug_symbols=yes separate_debug_symbols=yes"
export TERM=xterm
export PATH="${GODOT_SDK_LINUX_X86_64}/bin:${BASE_PATH}"

cd /root/godot
# drop <target>: that target's objects, once its binaries are copied (a build tree is ~3 GB a target).
drop() { find . \( -name "*.linuxbsd.$1.*.o" -o -name "*.linuxbsd.$1.*.a" \) -delete; }

$SCONS platform=linuxbsd arch=x86_64 $OPTIONS target=editor
# The glue is generated by the editor itself, then the assemblies are built against it (Godot's own procedure).
bin/godot.linuxbsd.editor.double.x86_64.mono --headless --generate-mono-glue modules/mono/glue
./modules/mono/build_scripts/build_assemblies.py --godot-output-dir=./bin --godot-platform=linuxbsd --precision=double
mkdir -p /root/out/linux/tools-mono
cp -rp bin/* /root/out/linux/tools-mono/
rm -rf bin
drop editor

$SCONS platform=linuxbsd arch=x86_64 $OPTIONS target=template_debug
$SCONS platform=linuxbsd arch=x86_64 $OPTIONS $SYMBOLS target=template_release
mkdir -p /root/out/linux/templates-mono
cp -rp bin/* /root/out/linux/templates-mono/
rm -rf bin
drop template_debug
drop template_release
echo "Linux build done"
